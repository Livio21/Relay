/** Paints a host icon at a fixed optical size; callers own the 48dp hit area. */
@Composable
fun RelayIcon(
    icon: ImageVector,
    description: String?,
    modifier: Modifier = Modifier,
    tint: Color = RelayColors.Paper,
    size: Dp = 24.dp,
) {
    Image(
        painter = rememberVectorPainter(icon),
        contentDescription = description,
        colorFilter = ColorFilter.tint(tint),
        modifier = modifier.size(size),
    )
}

/** Icon-only action with a guaranteed 48dp target and an optional standard haptic. */
@Composable
fun RelayIconButton(
    icon: ImageVector,
    description: String,
    onClick: () -> Unit,
    modifier: Modifier = Modifier,
    tint: Color = RelayColors.Paper,
    size: Dp = 24.dp,
    hapticAction: HapticAction? = HapticAction.TRANSPORT_PRESS,
) {
    val haptics = LocalRelayHaptics.current
    Box(
        modifier = modifier
            .size(48.dp)
            .semantics { contentDescription = description }
            .clickable(role = Role.Button) {
                hapticAction?.let(haptics::perform)
                onClick()
            },
        contentAlignment = Alignment.Center,
    ) {
        RelayIcon(icon, description = null, tint = tint, size = size)
    }
}
